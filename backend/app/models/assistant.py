from __future__ import annotations

import enum
import uuid
from datetime import date, datetime, time
from typing import TYPE_CHECKING, Optional

from sqlalchemy import (
    Date,
    DateTime,
    Float,
    ForeignKey,
    Index,
    Integer,
    String,
    Text,
    Time,
    Uuid,
)
from sqlalchemy import (
    Enum as SQLEnum,
)
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.models.alarm import TransportMode
from app.models.base import Base, TimestampMixin

if TYPE_CHECKING:
    from app.models.destination import Destination
    from app.models.user import User


class DraftStatus(str, enum.Enum):
    DRAFT = "draft"
    CONFIRMED = "confirmed"
    DISCARDED = "discarded"


class AssistantConversation(Base, TimestampMixin):
    """
    Persistent conversational session between the authenticated user and ADA Assistant.
    Supports user privacy controls (deletion, retention policies, opt-out).
    """

    __tablename__ = "assistant_conversations"

    id: Mapped[uuid.UUID] = mapped_column(
        Uuid, primary_key=True, default=uuid.uuid4, index=True
    )
    user_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"), nullable=False, index=True
    )
    title: Mapped[str] = mapped_column(String(255), default="New Conversation", nullable=False)

    # Relationships
    user: Mapped["User"] = relationship("User")
    messages: Mapped[list["AssistantMessage"]] = relationship(
        "AssistantMessage",
        back_populates="conversation",
        cascade="all, delete-orphan",
        order_by="AssistantMessage.created_at.asc()",
    )
    drafts: Mapped[list["AlarmDraft"]] = relationship(
        "AlarmDraft",
        back_populates="conversation",
        cascade="all, delete-orphan",
    )


class AssistantMessage(Base, TimestampMixin):
    """Individual conversational turn within an Assistant Conversation."""

    __tablename__ = "assistant_messages"

    id: Mapped[uuid.UUID] = mapped_column(
        Uuid, primary_key=True, default=uuid.uuid4, index=True
    )
    conversation_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("assistant_conversations.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    user_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"), nullable=False, index=True
    )
    role: Mapped[str] = mapped_column(String(20), nullable=False)  # "user", "assistant", "system"
    content: Mapped[str] = mapped_column(Text, nullable=False)
    metadata_json: Mapped[Optional[str]] = mapped_column(Text, nullable=True)

    # Relationships
    conversation: Mapped["AssistantConversation"] = relationship(
        "AssistantConversation", back_populates="messages"
    )
    user: Mapped["User"] = relationship("User")


class AlarmDraft(Base, TimestampMixin):
    """
    Structured, editable draft of an alarm generated by the intent parser and deterministic ETA engine.
    NEVER converted into a real scheduled alarm without explicit user confirmation.
    """

    __tablename__ = "alarm_drafts"

    id: Mapped[uuid.UUID] = mapped_column(
        Uuid, primary_key=True, default=uuid.uuid4, index=True
    )
    user_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"), nullable=False, index=True
    )
    conversation_id: Mapped[Optional[uuid.UUID]] = mapped_column(
        ForeignKey("assistant_conversations.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )

    title: Mapped[str] = mapped_column(String(150), default="Smart Alarm Draft", nullable=False)
    destination_text: Mapped[str] = mapped_column(String(500), nullable=False)
    destination_id: Mapped[Optional[uuid.UUID]] = mapped_column(
        ForeignKey("destinations.id", ondelete="SET NULL"), nullable=True, index=True
    )
    destination_address: Mapped[Optional[str]] = mapped_column(String(500), nullable=True)
    destination_lat: Mapped[Optional[float]] = mapped_column(Float, nullable=True)
    destination_lng: Mapped[Optional[float]] = mapped_column(Float, nullable=True)

    # Schedule parameters
    arrival_time: Mapped[time] = mapped_column(Time, nullable=False)
    arrival_date: Mapped[Optional[date]] = mapped_column(Date, nullable=True)
    preparation_time: Mapped[int] = mapped_column(Integer, default=30, nullable=False)  # minutes
    safety_buffer: Mapped[int] = mapped_column(Integer, default=15, nullable=False)  # minutes
    transportation_mode: Mapped[TransportMode] = mapped_column(
        SQLEnum(
            TransportMode,
            name="transport_mode_enum",
            values_callable=lambda x: [e.value for e in x],
        ),
        default=TransportMode.DRIVING,
        nullable=False,
    )
    timezone: Mapped[str] = mapped_column(String(50), default="Asia/Kolkata", nullable=False)

    # Deterministic Engine Outputs (populated by ETA engine, never by LLM)
    calculated_wake_time: Mapped[Optional[datetime]] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    calculated_leave_time: Mapped[Optional[datetime]] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    planned_arrival_time: Mapped[Optional[datetime]] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    travel_duration_minutes: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    traffic_delay_minutes: Mapped[int] = mapped_column(Integer, default=0, nullable=False)

    # State & Verification
    status: Mapped[DraftStatus] = mapped_column(
        SQLEnum(
            DraftStatus,
            name="draft_status_enum",
            values_callable=lambda x: [e.value for e in x],
        ),
        default=DraftStatus.DRAFT,
        nullable=False,
        index=True,
    )
    explanation: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    idempotency_key: Mapped[Optional[str]] = mapped_column(String(100), nullable=True, index=True)

    # Relationships
    user: Mapped["User"] = relationship("User")
    conversation: Mapped[Optional["AssistantConversation"]] = relationship(
        "AssistantConversation", back_populates="drafts"
    )
    destination: Mapped[Optional["Destination"]] = relationship("Destination")

    __table_args__ = (
        Index("ix_alarm_drafts_user_id_status", "user_id", "status"),
    )
